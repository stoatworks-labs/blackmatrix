// Release signing, read from a file that is NOT in the repo.
//
// keystore.properties and the .jks it points at are gitignored: a signing key is
// the identity of every future update, and Android will refuse an update signed
// by a different one. Losing it means a new package name.
//
// When the file is absent — which it is for anyone who has just cloned this —
// the release build stays unsigned rather than failing, so `assembleDebug` and
// CI keep working. See docs/signing.md.
val keystoreProperties = Properties().apply {
    val propFile = rootProject.file("keystore.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}
val hasKeystore = keystoreProperties.getProperty("storeFile") != null

android {
    compileSdk = 36
    namespace = "com.allansargeant.blackmatrix.mobile"
    defaultConfig {
        // Tauri's template sets this false for release. For this app that would
        // mean a release build silently cannot reach any server: a BlackMatrix
        // server is plain http on a private address, which is what a show
        // network is. Same reasoning as NSAllowsLocalNetworking on iOS, and the
        // same failure mode if omitted — it works in debug and dies in release.
        manifestPlaceholders["usesCleartextTraffic"] = "true"
        applicationId = "com.allansargeant.blackmatrix.mobile"
        minSdk = 24
        targetSdk = 36
        versionCode = tauriProperties.getProperty("tauri.android.versionCode", "1").toInt()
        versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")
    }
    signingConfigs {
        if (hasKeystore) {
            create("release") {
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
                storeFile = file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
            }
        }
    }
    buildTypes {
        getByName("debug") {
            manifestPlaceholders["usesCleartextTraffic"] = "true"
            isDebuggable = true
            isJniDebuggable = true
            isMinifyEnabled = false
            packaging {                jniLibs.keepDebugSymbols.add("*/arm64-v8a/*.so")
                jniLibs.keepDebugSymbols.add("*/armeabi-v7a/*.so")
                jniLibs.keepDebugSymbols.add("*/x86/*.so")
                jniLibs.keepDebugSymbols.add("*/x86_64/*.so")
            }
        }
        getByName("release") {
            if (hasKeystore) {
                signingConfig = signingConfigs.getByName("release")
            }
            isMinifyEnabled = true
            proguardFiles(
                *fileTree(".") { include("**/*.pro") }
                    .plus(getDefaultProguardFile("proguard-android-optimize.txt"))
                    .toList().toTypedArray()
            )
        }
    }
    kotlinOptions {
        jvmTarget = "1.8"
    }
    buildFeatures {
        buildConfig = true
    }
}

